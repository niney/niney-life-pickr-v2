/** 흔한 한 끼의 정규화 이름 — 메뉴 어휘의 표기 변형(계란↔달걀·돈까스↔돈가스·둣국↔두국)까지. */
export const commonMealNorms = (lex: Lexicon): Set<string> => {
  const out = new Set<string>();
  for (const names of Object.values(COMMON_MEALS)) {
    for (const name of names) {
      const norm = normalizeTerm(name);
      if (!norm) continue;
      out.add(norm);
      for (const variant of synonymVariants(norm, lex)) out.add(variant);
    }
  }
  return out;
};
