export const weatherPlaceById = (id: string | null | undefined): WeatherPlace | null =>
  id ? (PLACE_BY_ID.get(id) ?? null) : null;

export const weatherMidLandRegionById = (regId: string | null | undefined): WeatherMidLandRegion | null =>
  regId ? (LAND_BY_ID.get(regId) ?? null) : null;

// 지점이 속한 중기육상 구역 + 중기전망 stnId. 모르는 지점은 null.
export const weatherMidRegionForPlace = (
  place: WeatherPlace | null | undefined,
): { land: WeatherMidLandRegion; stnId: string } | null => {
  const land = place ? LAND_BY_ID.get(place.landRegId) : undefined;
  return land ? { land, stnId: land.stnId } : null;
};

