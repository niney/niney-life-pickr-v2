export const TAROT_SUITS = ['wands', 'cups', 'swords', 'pentacles'] as const;
export type TarotSuit = (typeof TAROT_SUITS)[number];

export const TAROT_ELEMENTS = ['fire', 'water', 'air', 'earth'] as const;
export type TarotElement = (typeof TAROT_ELEMENTS)[number];

export const TAROT_COURT_RANKS = ['page', 'knight', 'queen', 'king'] as const;
export type TarotCourtRank = (typeof TAROT_COURT_RANKS)[number];

export type TarotArcana = 'major' | 'minor';

export interface TarotCard {
  id: string;
  arcana: TarotArcana;
  suit: TarotSuit | null;
  // 메이저 0~21. 마이너 1(에이스)~10, 궁정 11 페이지·12 나이트·13 퀸·14 킹. 덱 정렬 키.
  number: number;
  nameKo: string;
  nameEn: string;
  element: TarotElement;
  keywordsUpright: readonly string[];
  keywordsReversed: readonly string[];
  meaningUpright: string;
  meaningReversed: string;
}

export const TAROT_SUIT_META: Record<TarotSuit, { ko: string; en: string; element: TarotElement }> = {
  wands: { ko: '완드', en: 'Wands', element: 'fire' },
  cups: { ko: '컵', en: 'Cups', element: 'water' },
  swords: { ko: '소드', en: 'Swords', element: 'air' },
  pentacles: { ko: '펜타클', en: 'Pentacles', element: 'earth' },
};

export const TAROT_ELEMENT_LABEL: Record<TarotElement, string> = {
  fire: '불',
  water: '물',
  air: '바람',
  earth: '땅',
};

const pad2 = (n: number): string => String(n).padStart(2, '0');

const major = (
  number: number,
  nameKo: string,
  nameEn: string,
  element: TarotElement,
  keywordsUpright: readonly string[],
  keywordsReversed: readonly string[],
  meaningUpright: string,
  meaningReversed: string,
): TarotCard => ({
  id: `major-${pad2(number)}`,
  arcana: 'major',
  suit: null,
  number,
  nameKo,
  nameEn,
  element,
  keywordsUpright,
  keywordsReversed,
  meaningUpright,
  meaningReversed,
});

const RANK_EN = ['', 'Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Page', 'Knight', 'Queen', 'King'] as const;
const RANK_KO = ['', '에이스', '2', '3', '4', '5', '6', '7', '8', '9', '10', '페이지', '나이트', '퀸', '킹'] as const;
const RANK_ID = ['', '01', '02', '03', '04', '05', '06', '07', '08', '09', '10', 'page', 'knight', 'queen', 'king'] as const;

const minor = (
  suit: TarotSuit,
  number: number,
  keywordsUpright: readonly string[],
  keywordsReversed: readonly string[],
  meaningUpright: string,
  meaningReversed: string,
): TarotCard => {
  const meta = TAROT_SUIT_META[suit];
  return {
    id: `${suit}-${RANK_ID[number]}`,
    arcana: 'minor',
    suit,
    number,
    nameKo: `${meta.ko} ${RANK_KO[number]}`,
    nameEn: `${RANK_EN[number]} of ${meta.en}`,
    element: meta.element,
    keywordsUpright,
    keywordsReversed,
    meaningUpright,
    meaningReversed,
  };
};

